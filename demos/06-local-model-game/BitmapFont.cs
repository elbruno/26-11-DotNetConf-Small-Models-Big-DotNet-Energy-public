    public static void DrawText(
        SpriteBatch batch,
        Texture2D pixel,
        string text,
        int x,
        int y,
        int scale,
        Color color)
    {
        var startX = x;
        foreach (var character in text.ToUpperInvariant())
        {
            if (character == '\n')
            {
                x = startX;
                y += 9 * scale;
                continue;
            }

            if (Glyphs.TryGetValue(character, out var rows))
            {
                for (var row = 0; row < rows.Length; row++)
                {
                    for (var column = 0; column < rows[row].Length; column++)
                    {
                        if (rows[row][column] == '1')
                        {
                            batch.Draw(
                                pixel,
                                new Rectangle(x + column * scale, y + row * scale, scale, scale),
                                color);
                        }
                    }
                }
            }

            x += 6 * scale;
        }
    }

    public static string WrapText(string text, int maximumCharacters)
    {
        var lines = new List<string>();
        var line = new StringBuilder();

        foreach (var word in text.ToUpperInvariant().Split(' ', StringSplitOptions.RemoveEmptyEntries))
        {
            if (line.Length > 0 && line.Length + word.Length + 1 > maximumCharacters)
            {
                lines.Add(line.ToString());
                line.Clear();
            }

            if (line.Length > 0)
            {
                line.Append(' ');
            }

            line.Append(word);
        }

        if (line.Length > 0)
        {
            lines.Add(line.ToString());
        }

        return string.Join('\n', lines);
    }
